// kabu-watch PWA service worker
// Caches only the same-origin app shell so the app can be added to the
// home screen and reopen instantly. Stock data / OCR requests (Yahoo
// Finance, jsDelivr CDN) always go to the network — never cached here,
// since prices must stay fresh and CDN assets are cached by the browser
// HTTP cache / Tesseract's own IndexedDB cache already.

const CACHE = "kabu-watch-shell-v2";
const SHELL = [
  "./scan.html",
  "./manifest.webmanifest",
  "./icon-192.png",
  "./icon-512.png",
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(SHELL)).catch(() => {})
  );
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))
    )
  );
  self.clients.claim();
});

self.addEventListener("fetch", (event) => {
  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin) return; // never touch cross-origin
  if (event.request.method !== "GET") return;

  event.respondWith(
    fetch(event.request)
      .then((res) => {
        const copy = res.clone();
        caches.open(CACHE).then((cache) => cache.put(event.request, copy)).catch(() => {});
        return res;
      })
      .catch(() => caches.match(event.request))
  );
});
